def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


# --- held-out access and integrity ----------------------------------------------------------------

def heldout_files() -> list[Path]:
    base = BENCH / "heldout"
    return sorted([*(base / "companies").glob("*.json"), *(base / "forms").glob("*.txt")])


def heldout_digest_lines() -> list[str]:
    return [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(BENCH / 'heldout').as_posix()}"
            for p in heldout_files()]


def assert_heldout_frozen() -> None:
    if not FROZEN.exists():
        raise PermissionError("the held-out split is not frozen; it cannot be run or scored (checkpoint A1 first)")
    recorded = [l for l in FROZEN.read_text(encoding="utf-8").splitlines() if l and not l.startswith("#")]
    if recorded != heldout_digest_lines():
        raise PermissionError("held-out files differ from heldout/FROZEN.sha256; refusing to run")


def company_values(split: str, s: dict) -> dict:
    if split == "dev":
        return spec.defaults(s)
    form = BENCH / "heldout" / "forms" / f"{s['code']}.txt"
    return spec.parse_form(form.read_text(encoding="utf-8"))


def compile_split(split: str, allow_heldout: bool = False) -> list[dict]:
    if split == "heldout":
        if not allow_heldout:
            raise PermissionError("the held-out split is not available to development tools")
    elif split != "dev":
        raise PermissionError(f"unknown benchmark split {split!r}")
    out = []
    for s in spec.load_specs(BENCH / split / "companies"):
        values = company_values(split, s)
        problems = spec.consistency_problems(s, values)
        if problems:
            raise ValueError(f"{s['code']}: " + "; ".join(problems))
        out.append(spec.compile_company(s, values, CLOCK))
    return out


# --- network guard -------------------------------------------------------------------------------

@contextlib.contextmanager
def no_network(blocked: list, allow_hosts: tuple = ()):
    """Block every outbound connection except to localhost and, for the authorized live layer only, to the
    addresses that DNS returned for the named hosts (for example api.openai.com). Offline runs allow none."""
    original, original_gai = socket.socket.connect, socket.getaddrinfo
    allowed_ips: set = set()

    def gai(host, *a, **kw):
        res = original_gai(host, *a, **kw)
        if host in allow_hosts:
            allowed_ips.update(r[4][0] for r in res)
        return res

    def guarded(self, address):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost") and host not in allowed_ips:
            blocked.append(str(address))
            raise OSError(f"network blocked in the benchmark: {address}")
        return original(self, address)

    socket.socket.connect = guarded
    if allow_hosts:
        socket.getaddrinfo = gai
    try:
        yield
    finally:
        socket.socket.connect, socket.getaddrinfo = original, original_gai


# --- fixture news ----------------------------------------------------------------------------------

class FixtureNewsClient:
    """Same interface as TavilyClient.search. Returns every fixture item for the company named in the query
    (worst case: as if the provider ignored the date filter), so the pipeline's own filters are tested."""

    def __init__(self, items: dict, config=None):
        from deal_prep.web_research import SearchConfig
        self.items, self.config = items, config or SearchConfig()

    def search(self, payload, budget, today, trace):
        budget.reserve(1, today)
        name = payload["query"].removesuffix(" news")
        results = [{k: it[k] for k in ("title", "url", "published_date", "score", "content")}
                   for it in self.items.get(name, [])]
        trace.append({"service": "fixture", "query": payload["query"], "window": payload.get("start_date"),
                      "outcome": "ok", "results": len(results), "attempt": 1, "credits": 1, "elapsed_ms": 0})
        return {"results": results}


def news_id(url: str) -> str:
    """The evidence ID production code gives a web result (web_research.to_evidence)."""
    return "WEB-" + hashlib.sha1(url.encode()).hexdigest()[:12]


# --- isolated environment --------------------------------------------------------------------------

@contextlib.contextmanager
def benchmark_environment(compiled: list[dict], work: Path):
    """Redirect the knowledge base, registry and index locations to `work` inside this process only."""
    from deal_prep import config, demo, disclosures, index, kb_index, orchestrator, provenance, web_research
    import deal_prep.app_service as app_service
    import deal_prep.history_index as history_index

    work = work.resolve()
    if RUNS.resolve() not in work.parents:
        raise IsolationError(f"benchmark work folder must be under {RUNS}")
    corpus = work / "corpus"
    if corpus.exists():
        shutil.rmtree(corpus)
    vendor = [d for d in load_json(kb_index.KB_MANIFEST)["documents"] if d["scope"] == "global"]
    for d in vendor:
        (corpus / d["file_path"]).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(kb_index.KB_DIR / d["file_path"], corpus / d["file_path"])
    bench_docs = [doc for c in compiled for doc in c["documents"]]
    for doc in bench_docs:
        path = corpus / doc["manifest"]["file_path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(doc["text"], encoding="utf-8", newline="\n")
    production = load_json(provenance.REGISTRY_PATH)["organizations"]
    registry = {o["org_id"]: o for o in [o for o in production if o["reality"] == "fictional"]
                + [r for c in compiled for r in c["registry"]]}
    for o in registry.values():
        if o["reality"] == "real" and not (o.get("benchmark_fictional") and o["official_domain"].endswith(".example")):
            raise IsolationError(f"organization {o['org_id']} is not a fictional benchmark entity")
    manifest = vendor + [doc["manifest"] for doc in bench_docs]
    chroma = work / "chroma"
    real_client = index._client

    def guarded_client(path, *a, **kw):
        p = Path(path).resolve()
        if p != chroma and chroma not in p.parents:
            raise IsolationError(f"benchmark tried to open an index outside its work folder: {p}")
        return real_client(path, *a, **kw)

    reg = lambda *a, **kw: {k: dict(v) for k, v in registry.items()}  # noqa: E731
    man = lambda *a, **kw: [dict(d) for d in manifest]  # noqa: E731
    patches = [
        mock.patch.object(provenance, "load_registry", reg), mock.patch.object(kb_index, "load_registry", reg),
        mock.patch.object(orchestrator, "load_registry", reg), mock.patch.object(web_research, "load_registry", reg),
        mock.patch.object(kb_index, "load_manifest", man), mock.patch.object(disclosures, "load_manifest", man),
        mock.patch.object(orchestrator, "load_manifest", man),
        mock.patch.object(kb_index, "KB_DIR", corpus), mock.patch.object(config, "CHROMA_DIR", chroma),
        mock.patch.object(index, "_client", guarded_client), mock.patch.object(kb_index, "_client", guarded_client),
        mock.patch.object(history_index, "_client", guarded_client),
        mock.patch.object(app_service, "_client", guarded_client),
    ]
    with contextlib.ExitStack() as stack:
        for p in patches:
            stack.enter_context(p)
        demo._kb_structure.cache_clear()  # the template's corpus lookup must see the benchmark corpus
        try:
            yield {"chroma": chroma, "corpus": corpus, "registry": registry, "manifest": manifest}
        finally:
            demo._kb_structure.cache_clear()


# --- stable references -----------------------------------------------------------------------------

def resolve_refs(refs: set[str], chunks: dict[str, str]) -> tuple[dict, list[str]]:
    """Map stable references to passage IDs. Returns (tokens, problems). A reference must match exactly one passage."""
    tokens, problems = {}, []
    for ref in sorted(r for r in refs if not r.startswith(("NEWS:", "HIST:"))):
        if "~" in ref:
            doc, text = ref.split("~", 1)
            hits = [cid for cid, t in chunks.items() if cid.split("#")[0] == doc and text in t]
        else:
            doc, part = ref.split(":", 1)
            marker = "[C1]" if part == "CLAIMS" else f"[{part}]"
            hits = [cid for cid, t in chunks.items() if cid.split("#")[0] == doc and marker in t]
        if len(hits) != 1:
            problems.append(f"reference {ref} matches {len(hits)} passages (must be exactly 1)")
        else:
            tokens[ref] = hits[0]
    return tokens, problems


def expected_refs(exp: dict) -> set[str]:
    refs = set()

    def walk(x):
        if isinstance(x, str) and re.match(r"^(NVQ-|NEWS:|HIST:)", x):
            refs.add(x)
        elif isinstance(x, list):
            for y in x:
                walk(y)
        elif isinstance(x, dict):
            for y in x.values():
                walk(y)
    walk({k: v for k, v in exp.items() if k not in ("customer_evidence",)})
    return refs


def verify_expected(exp: dict, tokens: dict, full: dict) -> list[str]:
    """Expected outcomes must be consistent with the rendered evidence."""
    problems = [f"reference {r} is not resolved" for r in expected_refs(exp) if r not in tokens]
    for need in exp["required_open_items"]:
        texts = " ".join(full.get(tokens.get(r, ""), "") for r in need["evidence_any"])
        if not any(p in texts for p in need["phrases_any"]):
            problems.append(f"open item '{need['key']}': none of its phrases occurs in its evidence")
    return problems


# --- one scenario ----------------------------------------------------------------------------------

def seed_history(service, company: str, seed: list[dict]) -> dict:
    """Create the scenario's meeting history through the app's own service functions. The approved content is
    given explicitly by the seed (as if the user had reviewed and edited the proposal)."""
    company_id = service.company_id_for(company)
    meetings, tasks, drafts = {}, {}, []
    for m in seed:
        mid = service.add_meeting_draft(company_id, m["notes"], f"bench-{m['key']}", m.get("meeting_date"))
        if not m.get("approve"):
            drafts.append({"key": m["key"], "meeting_id": mid})
            continue
        specs = [{"description": t["description"], "op_id": f"bench-{t['key']}", "due_date": t.get("due_date")}
                 for t in m.get("tasks", [])]
        ids = service.approve_meeting(mid, m["approved"], specs)
        meetings[m["key"]] = mid
        for t, tid in zip(m.get("tasks", []), ids):
            if t["final_status"] != "Open":
                service.set_task_status(tid, t["final_status"])
            tasks[t["key"]] = {"task_id": tid, "meeting": m["key"], "description": t["description"],
                               "status": t["final_status"], "due_date": t.get("due_date")}
    return {"company_id": company_id, "meetings": meetings, "tasks": tasks, "drafts": drafts}


def run_scenario(scenario: dict, compiled: list[dict], work: Path, news_mode: str = "news_fixture",
                 generate=None, decide=None, prices=None, allow_hosts: tuple = (),
                 repair_coverage: bool = False) -> dict:
    """Run one scenario in a fresh isolated work folder. Returns the run record (drafting input and output).
    By default the offline template drafter runs with no agent and no network. The authorized live layer
    (scripts/benchmark_live.py) passes the production OpenAI drafter and agent and allows only their API host."""
    from deal_prep import demo
    from deal_prep.app_service import BriefingService
    from deal_prep.history_index import meeting_text
    from deal_prep.kb_index import build_kb_index, load_kb_chunks
    from deal_prep.pipeline import prepare_briefing
    from deal_prep.web_research import Budget, SearchConfig

    if news_mode not in NEWS_MODES:
        raise ValueError(news_mode)
    company = next(c for c in compiled if any(sc["id"] == scenario["id"] for sc in c["scenarios"]))
    news = {scenario["company"]: company["news"]}
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    blocked = []
    with no_network(blocked, allow_hosts), benchmark_environment(compiled, work) as env:
        build_kb_index(chroma_dir=env["chroma"])
        service = BriefingService(chroma_dir=env["chroma"], history_path=work / "history.sqlite")
        hist = seed_history(service, scenario["company"], company["seed"]) if company["seed"] else \
            {"company_id": None, "meetings": {}, "tasks": {}, "drafts": []}
        company_id = hist["company_id"] or service.company_id_for(scenario["company"])
        client = FixtureNewsClient(news) if news_mode == "news_fixture" else demo.OfflineNewsClient()
        result = prepare_briefing(scenario["company"], news_client=client, budget=Budget(SearchConfig()),
                                  generate=generate or demo.TemplateDrafter(), decide=decide,
                                  domain=scenario.get("domain"), purpose=scenario["purpose"],
                                  chroma_dir=env["chroma"], now=CLOCK, run_id=f"{scenario['id']}-{news_mode}",
                                  prices=prices, repair_coverage=repair_coverage,
                                  history_search=service.history_search(company_id) if company_id else None)
        chunks = {c["chunk_id"]: c["text"] for c in load_kb_chunks()}
        full = dict(chunks)
        for it in company["news"]:
            full[news_id(it["url"])] = it["content"]
        for key, mid in hist["meetings"].items():
            full[f"HIST-{mid}#0"] = meeting_text(service.store.meeting(mid), service.store.tasks(meeting_id=mid))
    exp = company["expected"][(scenario["id"], news_mode)]
    tokens, problems = resolve_refs(expected_refs(exp), chunks)  # customer_evidence holds ID prefixes, not refs
    tokens.update({f"NEWS:{it['key']}": news_id(it["url"]) for it in company["news"]})
    tokens.update({f"HIST:{k}": f"HIST-{mid}#0" for k, mid in hist["meetings"].items()})
    problems += verify_expected(exp, tokens, full)
    if problems:
        raise ValueError(f"{scenario['id']} ({news_mode}): expected outcomes inconsistent with evidence: "
                         + "; ".join(problems))
    return {"scenario": scenario["id"], "news_mode": news_mode, "company": scenario["company"],
            "purpose": scenario["purpose"], "clock": CLOCK.isoformat(), "label": LABEL,
            "status": result["status"], "research_status": result["research_status"],
            "message": result.get("message", ""), "drafting_input": result.get("evidence", {}),
            "selection": result.get("selection"),  # I3: why each drafting-input passage is there (not scored)
            "coverage": result.get("coverage"),  # I3.1: essential topics communicated (not scored)
            "business_analysis": result.get("business_analysis"),  # I5: calculations with inputs (not scored)
            "section_notes": result.get("section_notes"),  # I6: the drafter's reason for each empty section (not scored)
            "briefing": result.get("briefing"), "disclosures": result.get("disclosures", []),
            "full_text": full, "tokens": tokens, "history": hist, "expected": exp, "blocked_connections": blocked,
            "mode": result.get("mode"), "usage": result.get("usage"), "agent": result.get("agent"),
            "citation_issues": result.get("citation_issues", []), "labels": result.get("labels")}


def canonical(record: dict) -> str:
    """The parts of a run record that must be identical between two offline runs."""
    keep = {k: record[k] for k in ("status", "research_status", "briefing", "disclosures")}
    keep["drafting_input"] = {k: v.get("excerpt") for k, v in sorted(record["drafting_input"].items())}
    text = json.dumps(keep, sort_keys=True, ensure_ascii=False)
    for tok, real in record["tokens"].items():  # meeting IDs are random per run: compare through their tokens
        if tok.startswith("HIST:"):
            text = text.replace(real.split("#")[0], tok)
    return text
